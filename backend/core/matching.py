INVITATION_SENT = "sent"
INVITATION_VIEWED = "viewed"
INVITATION_ACCEPTED = "accepted"
INVITATION_REJECTED = "rejected"
INVITATION_WITHDRAWN = "withdrawn"

INVITATION_TRANSITIONS = {
    INVITATION_SENT: {INVITATION_VIEWED, INVITATION_REJECTED, INVITATION_WITHDRAWN},
    INVITATION_VIEWED: {INVITATION_ACCEPTED, INVITATION_REJECTED, INVITATION_WITHDRAWN},
    INVITATION_ACCEPTED: set(),
    INVITATION_REJECTED: set(),
    INVITATION_WITHDRAWN: set(),
}

INVITATION_EDITABLE_STATUSES = {INVITATION_SENT}

VACANCY_OPEN = "open"
VACANCY_CLOSED = "closed"

APPLICATION_STATUSES = ["new", "viewed", "accepted", "rejected"]


def invitation_transition_allowed(current: str, new: str) -> bool:
    return new in INVITATION_TRANSITIONS.get(current, set())
